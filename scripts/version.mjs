#!/usr/bin/env node
/**
 * Single source of truth for the release version.
 *
 *   node scripts/version.mjs --check   # verify every file matches VERSION
 *   node scripts/version.mjs --sync    # rewrite generated/duplicated fields
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const VERSION = '1.2.5';
export const APPLICATION_ID = 'top.wikifactory.editor';

/** Deterministic versionCode: major*10000 + minor*100 + patch (CI passes it to Gradle). */
export function versionCodeFor(version = VERSION) {
  const [major = 0, minor = 0, patch = 0] = String(version)
    .split('.')
    .map((part) => Number.parseInt(part, 10) || 0);
  return major * 10000 + minor * 100 + patch;
}

export const VERSION_CODE = versionCodeFor(VERSION);

export function versionModuleSource(version = VERSION) {
  return [
    '// Generated by scripts/version.mjs --sync. Do not edit by hand.',
    `export const APP_VERSION = '${version}';`,
    `export const ANDROID_VERSION_CODE = ${versionCodeFor(version)};`,
    '',
  ].join('\n');
}

export function desktopManifestSource(version = VERSION) {
  return `${JSON.stringify(
    {
      applicationId: APPLICATION_ID,
      version,
      resourcesURL: `https://github.com/hellokug2699/Wikifactory-Editor/releases/download/v${version}/Wikifactory-Editor-v${version}-windows-x64-resources.neu`,
    },
    null,
    2,
  )}\n`;
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function writeJson(file, data) {
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
}

/** @returns {string[]} problems (empty when consistent) */
export function checkVersionFiles(root) {
  const problems = [];
  const pkg = readJson(path.join(root, 'package.json'));
  if (pkg.version !== VERSION) problems.push(`package.json 版本 ${pkg.version} ≠ ${VERSION}`);

  const pm = readJson(path.join(root, 'package-lock.json'));
  if (pm.version !== VERSION) problems.push(`package-lock.json 版本 ${pm.version} ≠ ${VERSION}`);
  if (pm.packages?.['']?.version !== VERSION) {
    problems.push(`package-lock.json packages[""].version ≠ ${VERSION}`);
  }

  const versionFile = path.join(root, 'app/assets/js/version.js');
  const expected = versionModuleSource();
  if (!fs.existsSync(versionFile) || fs.readFileSync(versionFile, 'utf8') !== expected) {
    problems.push('app/assets/js/version.js 未同步（运行 npm run version:sync）');
  }

  const desktop = readJson(path.join(root, 'desktop/neutralino.config.json'));
  if (desktop.version !== VERSION) problems.push(`neutralino.config.json 版本 ${desktop.version} ≠ ${VERSION}`);
  if (desktop.applicationId !== APPLICATION_ID) {
    problems.push(`neutralino.config.json applicationId ≠ ${APPLICATION_ID}`);
  }

  const gradlePath = path.join(root, 'android/app/build.gradle');
  const gradle = fs.readFileSync(gradlePath, 'utf8');
  const fallbackCode = /findProperty\('appVersionCode'\)\s*\?:\s*'(\d+)'/.exec(gradle);
  const fallbackName = /findProperty\('appVersionName'\)\s*\?:\s*'([^']+)'/.exec(gradle);
  if (!/versionCode\s+appVersionCode/.test(gradle) || !/versionName\s+appVersionName/.test(gradle)) {
    problems.push('build.gradle 未使用 appVersionCode / appVersionName 属性');
  }
  if (!fallbackCode || Number(fallbackCode[1]) !== VERSION_CODE) {
    problems.push(`build.gradle 兜底 versionCode ≠ ${VERSION_CODE}`);
  }
  if (!fallbackName || fallbackName[1] !== VERSION) {
    problems.push(`build.gradle 兜底 versionName ≠ ${VERSION}`);
  }

  const manifestPath = path.join(root, 'updates/desktop.json');
  const manifestSource = desktopManifestSource();
  if (!fs.existsSync(manifestPath) || fs.readFileSync(manifestPath, 'utf8') !== manifestSource) {
    problems.push('updates/desktop.json 未同步');
  }

  const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
  if (!readme.includes(`## 下载（v${VERSION}）`)) problems.push(`README 下载章节不是 v${VERSION}`);
  if (!readme.includes(`## v${VERSION} `)) problems.push(`README 缺少 v${VERSION} 更新章节`);

  return problems;
}

export function syncVersionFiles(root) {
  const changed = [];

  const pkgPath = path.join(root, 'package.json');
  const pkg = readJson(pkgPath);
  if (pkg.version !== VERSION) {
    pkg.version = VERSION;
    writeJson(pkgPath, pkg);
    changed.push('package.json');
  }

  const lockPath = path.join(root, 'package-lock.json');
  const lock = readJson(lockPath);
  let lockChanged = false;
  if (lock.version !== VERSION) {
    lock.version = VERSION;
    lockChanged = true;
  }
  if (lock.packages?.['']) {
    if (lock.packages[''].version !== VERSION) {
      lock.packages[''].version = VERSION;
      lockChanged = true;
    }
  }
  if (lockChanged) {
    writeJson(lockPath, lock);
    changed.push('package-lock.json');
  }

  const versionFile = path.join(root, 'app/assets/js/version.js');
  const expected = versionModuleSource();
  if (!fs.existsSync(versionFile) || fs.readFileSync(versionFile, 'utf8') !== expected) {
    fs.writeFileSync(versionFile, expected);
    changed.push('app/assets/js/version.js');
  }

  const desktopPath = path.join(root, 'desktop/neutralino.config.json');
  const desktop = readJson(desktopPath);
  if (desktop.version !== VERSION || desktop.applicationId !== APPLICATION_ID) {
    desktop.version = VERSION;
    desktop.applicationId = APPLICATION_ID;
    writeJson(desktopPath, desktop);
    changed.push('desktop/neutralino.config.json');
  }

  const gradlePath = path.join(root, 'android/app/build.gradle');
  const gradle = fs.readFileSync(gradlePath, 'utf8');
  const next = gradle
    .replace(/(findProperty\('appVersionCode'\)\s*\?:\s*')\d+(')/, `$1${VERSION_CODE}$2`)
    .replace(/(findProperty\('appVersionName'\)\s*\?:\s*')[^']+(')/, `$1${VERSION}$2`);
  if (next !== gradle) {
    fs.writeFileSync(gradlePath, next);
    changed.push('android/app/build.gradle');
  }

  const manifestDir = path.join(root, 'updates');
  const manifestPath = path.join(manifestDir, 'desktop.json');
  const manifestSource = desktopManifestSource();
  if (!fs.existsSync(manifestPath) || fs.readFileSync(manifestPath, 'utf8') !== manifestSource) {
    fs.mkdirSync(manifestDir, { recursive: true });
    fs.writeFileSync(manifestPath, manifestSource);
    changed.push('updates/desktop.json');
  }

  return changed;
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const sync = process.argv.includes('--sync');
  if (sync) {
    const changed = syncVersionFiles(root);
    console.log(changed.length ? `[version] 已同步：${changed.join('、')}` : '[version] 已是最新。');
  }
  const problems = checkVersionFiles(root);
  if (problems.length) {
    console.error('[version] 版本不一致：');
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exit(1);
  }
  console.log(`[version] v${VERSION}（versionCode ${VERSION_CODE}）一致。`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
